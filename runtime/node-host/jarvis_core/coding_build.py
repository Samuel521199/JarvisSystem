def executable(selected):
    return selected in {ZIPAPP, DEPENDENCY, coding_js.RECIPE, *coding_package.RECIPES}


def uses_dependencies(selected):
    return selected in {DEPENDENCY, coding_package.QUERY}


def validate_sources(sources, entry, selected):
    if selected == coding_js.RECIPE: return coding_js.validate(sources, entry)
    extra = dependencies.IMPORTS if uses_dependencies(selected) else None
    if selected in coding_package.RECIPES: return coding_package.validate(sources, entry, extra=extra)
    return validate_bundle(sources, entry, imports=extra)

