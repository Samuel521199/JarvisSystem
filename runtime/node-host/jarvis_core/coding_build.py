def recipe(value):
    if not isinstance(value, str) or value not in RECIPES:
        raise policy.CoreError('coding_recipe_invalid', '请选择已登记的 Python 构建配方。')
    return value


def build(sources, entry, cases_digest, selected=SOURCE):
    recipe(selected)
    if selected == coding_js.RECIPE:
        raise policy.CoreError('coding_recipe_invalid','场景构建需要先隔离编译几何帧，请使用场景构建器。')
    if selected == SOURCE:
        return package(sources, entry, cases_digest)
    vendor = dependencies.members() if uses_dependencies(selected) else {}
    modules = validate_sources(sources, entry, selected)
    launcher, readme = (DEPENDENCY_MAIN, DEPENDENCY_README) if vendor else (MAIN, README)
    if selected in coding_package.RECIPES: launcher = coding_package.launcher(bool(vendor))
    manifest = {'kind': 'jarvis.python-zipapp', 'version': 1, 'recipe': selected,
                'entry': entry, 'dependency_install': False, 'python': '>=3.11,<3.14',
                'files': {p: policy.digest(s.encode()) for p, s in sorted(sources.items())},
                'launcher_sha256': policy.digest(launcher.encode()), 'cases_digest': cases_digest}
    if vendor:
        manifest.update(dependencies=[dependencies.lock()],
                        dependency_files={p: policy.digest(s.encode()) for p, s in sorted(vendor.items())})
    if modules is not None:
        manifest.update(modules=modules, entry_module=next(n for n,p in modules.items() if p==entry))
    stream = io.BytesIO()
    if set(sources) & set(vendor):
        raise policy.CoreError('coding_invalid', '源码路径不能覆盖已锁定依赖。')
    members = {**sources, **vendor, '__main__.py': launcher, 'README.txt': readme,
               'jarvis-build.json': policy.canonical_json(manifest)}
    with zipfile.ZipFile(stream, 'w') as archive:
        for name, content in sorted(members.items()):
            info = zipfile.ZipInfo(name, (2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, content.encode())
    raw = stream.getvalue()
    return {'manifest': manifest, 'sha256': policy.digest(raw), 'size_bytes': len(raw),
            'filename': RECIPES[ZIPAPP]['filename'], 'base64': base64.b64encode(raw).decode()}


def inspect(raw, expected_digest=None):
    """No extraction or execution: reject modified, oversized or ambiguous archives."""
    try:
        if not isinstance(raw, bytes) or not 1 <= len(raw) <= 65536:
            raise ValueError('archive size')
        if expected_digest is not None and policy.digest(raw) != expected_digest:
            raise ValueError('archive digest')
        with zipfile.ZipFile(io.BytesIO(raw)) as archive:
            infos = archive.infolist()
            names = [i.filename for i in infos]
            if len(names) != len(set(names)) or not 2 <= len(names) <= 21:
                raise ValueError('members')
            if sum(i.file_size for i in infos) > 1024*1024 or any(i.flag_bits & 1 for i in infos):
                raise ValueError('expanded quota')
            manifest = json.loads(archive.read('jarvis-build.json'))
            if not isinstance(manifest, dict) or not isinstance(manifest.get('files'), dict):
                raise ValueError('manifest')
            selected = manifest.get('recipe')
            if selected == coding_js.RECIPE:
                from .coding_scene import inspect as inspect_scene
                return inspect_scene(raw, expected_digest)
            if sum(i.file_size for i in infos) > 131072 or any(i.file_size > 32768 for i in infos):
                raise ValueError('expanded quota')
            if selected == 'offline-python-lpac-v1': selected = SOURCE
            recipe(selected)
            if selected not in coding_package.RECIPES and selected != DEPENDENCY and (len(names) > 7 or sum(i.file_size for i in infos) > 49152):
                raise ValueError('legacy quota')
            expected = set(manifest['files']) | {'jarvis-build.json'}
            if executable(selected): expected |= {'__main__.py', 'README.txt'}
            if uses_dependencies(selected): expected |= set(dependencies.members())
            if set(names) != expected: raise ValueError('unexpected members')
            sources = {p: archive.read(p).decode('utf-8') for p in manifest['files']}
            rebuilt = build(sources, manifest['entry'], manifest['cases_digest'], selected)
            # Includes exact launcher, recipe, manifest, file digests and reproducible zip metadata.
            if base64.b64decode(rebuilt['base64']) != raw:
                raise ValueError('recipe/content mismatch')
            return sources, manifest['entry'], rebuilt
    except (ValueError, TypeError, KeyError, UnicodeError, RecursionError, zipfile.BadZipFile, policy.CoreError) as exc:
        raise policy.CoreError('coding_build_invalid', '构建包与固定配方不匹配、内容已变化或超出限制；未执行。') from exc


def bytes_from(build_value):
    try:
        encoded = build_value['base64']
        if not isinstance(encoded, str) or len(encoded) > 90000: raise ValueError()
        raw = base64.b64decode(encoded, validate=True)
        _, _, rebuilt = inspect(raw, build_value['sha256'])
        if rebuilt != build_value: raise ValueError('receipt mismatch')
        return raw
    except (KeyError, TypeError, ValueError, binascii.Error) as exc:
        raise policy.CoreError('coding_build_invalid', '构建包回执不匹配；未执行。') from exc


